def get_graph_levels(adj_matrix):
    """
    Разбивает вершины графа по уровням (ярусно-параллельная форма).
    Возвращает список множеств вершин для каждого уровня (нумерация с 1).
    """
    n = len(adj_matrix)

    # 1. Предвычисляем множество непосредственных предшественников для каждой вершины
    in_nodes = {j: {i for i in range(n) if adj_matrix[i][j] != 0} for j in range(n)}

    levels = []
    visited = set()

    # 2. Нулевой уровень — вершины-истоки (без входящих дуг)
    current_level = {j for j, preds in in_nodes.items() if not preds}

    while current_level:
        levels.append(current_level)
        visited.update(current_level)

        # 3. Следующий уровень: еще не распределенные вершины,
        # чьи предшественники целиком входят в уже пройденные уровни
        next_level = {
            j for j in range(n)
            if j not in visited and in_nodes[j].issubset(visited)
        }
        current_level = next_level

    if len(visited) != n:
        missing = set(range(n)) - visited
        print(f"Предупреждение: в графе есть циклы, не распределены вершины: { {v + 1 for v in missing} }")

    # Преобразуем индексы (0..n-1) в номера вершин (1..n)
    return [{v + 1 for v in lvl} for lvl in levels]


